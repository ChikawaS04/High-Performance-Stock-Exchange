package integration;

import config.ExchangeConfig;
import engine.CommandHandler;
import event.ExecutionEvent;
import event.ExecutionEventType;
import gateway.OrderGateway;
import journal.JournaledPipeline;
import model.Side;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.function.LongConsumer;

import static integration.ReporterHarness.cancel;
import static integration.ReporterHarness.limit;
import static integration.ReporterHarness.recordedEvents;
import static org.junit.jupiter.api.Assertions.*;

/**
 * D7 for {@code ExecutionEvent.commandSeq}: driven from raw FIX bytes through the sequencer and the
 * journal to the engine, recorded on the outbound stream, and regenerated by a recovery replay.
 */
class CommandSeqJournalTest {

    private static final long PRICE = 1_000_000L;

    @TempDir
    Path root;

    /** Inbound 1 opens; 2 rests; 3 fills 2 in full; 4 rests; 5 cancels it. */
    private static void script(OrderGateway gateway) {
        gateway.onFrame(limit(10L, Side.SELL, PRICE, 5L));
        gateway.onFrame(limit(11L, Side.BUY, PRICE, 5L));
        gateway.onFrame(limit(12L, Side.BUY, PRICE, 5L));
        gateway.onFrame(cancel(13L, 12L));
    }

    private static List<Long> commandSeqs(List<ExecutionEvent> events) {
        List<Long> seqs = new ArrayList<>();
        for (ExecutionEvent e : events) seqs.add(e.commandSeq);
        return seqs;
    }

    @Test
    void everyRecordedEventNamesTheCommandThatCausedIt() {
        try (JournaledVenue venue = JournaledVenue.create(root)) {
            OrderGateway gateway = venue.gateway();
            venue.startAndOpen(gateway);
            script(gateway);
            List<ExecutionEvent> events = recordedEvents(venue.journal(), 5);
            assertEquals(List.of(1L, 2L, 3L, 4L, 5L), commandSeqs(events));
            assertEquals(ExecutionEventType.ORDER_CANCELLED, events.get(4).eventType);
        }
    }

    @Test
    void oneCommandCausingSeveralEventsNamesItInEach() {
        try (JournaledVenue venue = JournaledVenue.create(root)) {
            OrderGateway gateway = venue.gateway();
            venue.startAndOpen(gateway);
            gateway.onFrame(limit(10L, Side.SELL, PRICE, 2L));
            gateway.onFrame(limit(11L, Side.SELL, PRICE, 2L));
            gateway.onFrame(limit(12L, Side.BUY, PRICE, 9L));   // two fills, then rests
            assertEquals(List.of(1L, 2L, 3L, 4L, 4L, 4L), commandSeqs(recordedEvents(venue.journal(), 6)));
        }
    }

    @Test
    void aTapWrappingTheEngineStillForwardsTheSeq() {
        CommandHandler tap = command -> { };
        try (JournaledVenue venue = JournaledVenue.create(root, tap)) {
            OrderGateway gateway = venue.gateway();
            venue.startAndOpen(gateway);
            script(gateway);
            assertEquals(List.of(1L, 2L, 3L, 4L, 5L), commandSeqs(recordedEvents(venue.journal(), 5)));
        }
    }

    /** Events the recorder never wrote are regenerated by replay, carrying the same seqs as a clean run. */
    @Test
    void aRecoveryReplayRegeneratesTheCommandSeqOfEventsTheRecorderLost() {
        ExchangeConfig config = JournaledVenue.config(root);
        LongConsumer failAtThree = seq -> {
            if (seq == 3L) throw new IllegalStateException("the recorder fails at seq 3");
        };
        JournaledVenue crashed = JournaledVenue.create(config, new JournaledPipeline.Seams(null, null, failAtThree));
        OrderGateway gateway = crashed.gateway();
        crashed.startAndOpen(gateway);
        script(gateway);
        ReporterHarness.await("the recorder to fail", () -> !crashed.fatals().isEmpty());
        ReporterHarness.await("the engine to apply every command",
                () -> crashed.pipeline().appliedSeq() >= 5L);
        crashed.closeAfterFatal();

        try (JournaledVenue again = JournaledVenue.create(config, JournaledPipeline.Seams.NONE)) {
            OrderGateway next = again.gateway();
            again.startAndOpen(next);
            List<ExecutionEvent> events = recordedEvents(again.journal(), 5);
            assertEquals(List.of(1L, 2L, 3L, 4L, 5L), commandSeqs(events));
            assertTrue(events.size() == 5);
        }
    }

    /** A restart compares the recorded event at the floor, command seq included, and refuses nothing. */
    @Test
    void aCleanRestartAgreesWithTheRecordedCommandSeqs() {
        ExchangeConfig config = JournaledVenue.config(root);
        try (JournaledVenue venue = JournaledVenue.create(config, JournaledPipeline.Seams.NONE)) {
            OrderGateway gateway = venue.gateway();
            venue.startAndOpen(gateway);
            script(gateway);
            recordedEvents(venue.journal(), 5);
        }
        try (JournaledVenue again = JournaledVenue.create(config, JournaledPipeline.Seams.NONE)) {
            OrderGateway gateway = again.gateway();
            again.startAndOpen(gateway);
            gateway.onFrame(limit(20L, Side.BUY, PRICE, 1L));
            assertEquals(List.of(1L, 2L, 3L, 4L, 5L, 6L), commandSeqs(recordedEvents(again.journal(), 6)));
        }
    }
}
